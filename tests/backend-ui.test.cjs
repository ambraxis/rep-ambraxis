const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
test('assistente exige ativo da empresa e sincroniza seleção com cadastro',()=>{
 const listeners={};
 const ctx=vm.createContext({setInterval:()=>0,st:{page:'gps'},location:{protocol:'file:'},pages:{installation:()=>''},groups:[[],[],[],[null,[]]],menuIndex:{},ins:{fields:{asset:'VFT-001'}},document:{addEventListener:(type,fn)=>(listeners[type]??=[]).push(fn)},navigate:()=>{},parseHash:()=>{},render:()=>{},renderPage:()=>{},esc:s=>String(s).replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('"','&quot;'),linkBtn:()=>'',head:()=>'',panel:(t,b)=>t+b,tb:(h,r)=>r.join(''),row:r=>r.join('|'),badge:s=>s});
 vm.runInContext(fs.readFileSync(path.join(__dirname,'../backend.js'),'utf8'),ctx);
 vm.runInContext("backend.user={company:'Empresa A',role:'admin'};backend.assets=[{id:'CAM-001',name:'Caminhão <A>'}];",ctx);
 let html=vm.runInContext('pages.installation()',ctx);
 assert.match(html,/Caminhão &lt;A>/);
 assert.match(html,/data-backend-save disabled/);
 listeners.change[0]({target:{matches:s=>s==='[data-backend-asset]',value:'CAM-001'}});
 assert.equal(vm.runInContext('ins.fields.asset',ctx),'CAM-001');
 assert.equal(vm.runInContext('ins.fields.customer',ctx),'Empresa A');
 html=vm.runInContext('pages.installation()',ctx);
 assert.doesNotMatch(html,/data-backend-save disabled/);
 vm.runInContext("backend.assets=[{id:'CAM-001',name:'Caminhão',active:0}];",ctx);
 assert.match(vm.runInContext('pages.installation()',ctx),/data-backend-save disabled/);
 vm.runInContext("backend.editDevice={id:'device',active:0}",ctx);
 assert.doesNotMatch(vm.runInContext('pages.installation()',ctx),/data-backend-save disabled/);
 vm.runInContext("location.protocol='http:';backend.query='CAM-001';",ctx);
 assert.match(vm.runInContext('backendPage()',ctx),/Caminhão/);
 vm.runInContext("backend.query='sem resultado';",ctx);
 assert.doesNotMatch(vm.runInContext('backendPage()',ctx),/Caminhão/);
 vm.runInContext(`backend.devices=[{id:'D1',model:'fmc130',active:1,fields:{asset:'CAM-001',name:'GPS',imei:'123456789012345'}}];backend.installations=[{device_id:'D1',asset_id:'OLD',model:'fmc130',checks:{manual:false},diagnostics:{power:'Falhou'},notes:'Anterior'},{device_id:'D1',asset_id:'CAM-001',model:'fmc130',checks:{manual:true},diagnostics:{power:'Aprovado'},notes:'<registro>'}];`,ctx);
 listeners.click[0]({target:{closest:s=>s==='[data-backend-edit-device]'?{dataset:{backendEditDevice:'D1'}}:null}});
 assert.equal(vm.runInContext('ins.checks.manual',ctx),true);
 assert.equal(vm.runInContext('ins.diag.power',ctx),'Aprovado');
 assert.match(vm.runInContext('pages.installation()',ctx),/&lt;registro>/);
 listeners.click[0]({target:{closest:s=>s==='[data-backend-new-device]'?{}:null}});
 assert.equal(vm.runInContext('Object.keys(ins.checks).length',ctx),0);
 assert.equal(vm.runInContext('ins.diag.power',ctx),'Pendente');
 vm.runInContext("backend.user.role='operator';backend.editDevice={id:'D1',active:1};ins.fields.asset='CAM-001';backend.query='';",ctx);
 assert.match(vm.runInContext('pages.installation()',ctx),/data-backend-save disabled/);
 const operatorPage=vm.runInContext('backendPage()',ctx);
 assert.doesNotMatch(operatorPage,/data-backend-form="users"/);
 assert.doesNotMatch(operatorPage,/data-backend-edit-asset=/);
 assert.match(operatorPage,/Consultar \/ checklist/);
 assert.equal(vm.runInContext("gpsFreshness(null).key",ctx),'none');
 assert.equal(vm.runInContext("gpsFreshness({recorded_at:'2026-10-31T00:00:00.000Z'},Date.parse('2026-10-31T00:05:00.000Z')).key",ctx),'recent');
 assert.equal(vm.runInContext("gpsFreshness({recorded_at:'2026-10-31T00:00:00.000Z'},Date.parse('2026-10-31T00:05:00.001Z')).key",ctx),'delayed');
 assert.equal(vm.runInContext("gpsFreshness({recorded_at:'2026-10-31T00:01:00.000Z'},Date.parse('2026-10-31T00:00:00.000Z')).key",ctx),'future');
 assert.match(vm.runInContext("csvCell('=SUM(1)')",ctx),/SUM/);
 assert.equal(vm.runInContext("csvCell('=SUM(1)').charAt(1)",ctx),"'");
 assert.equal(vm.runInContext("csvCell(-3.1)",ctx),'"-3.1"');
 const gps=vm.runInContext('gpsPage()',ctx);
 assert.match(gps,/Nenhum envio recebido/);
 assert.doesNotMatch(gps,/data-gps-token/);
 vm.runInContext("backend.user.role='admin';backend.gpsToken='test-token';",ctx);
 assert.match(vm.runInContext('gpsPage()',ctx),/test-token/);
 assert.match(vm.runInContext('operationalGeofencesPage()',ctx),/data-geofence-create/);
 vm.runInContext("backend.user.role='operator';backend.geofenceEvents=[{id:'event',zone_name:'Base <A>',asset_id:'A',device_id:'D1',kind:'exit',recorded_at:new Date().toISOString(),created_at:new Date().toISOString(),ack_at:null}];",ctx);
 const zonesPage=vm.runInContext('operationalGeofencesPage()',ctx);
 assert.doesNotMatch(zonesPage,/data-geofence-create/);assert.match(zonesPage,/data-geofence-ack/);assert.match(zonesPage,/Base &lt;A>/);
 vm.runInContext("backend.assets=[]",ctx);
 assert.match(vm.runInContext('pages.installation()',ctx),/data-backend-save disabled/);
});
